#!/usr/bin/env python3
"""Flattens the stroke alphabet of draw.py (LETTERS, SYMBOL_PATHS) into the table
src/game/keycap_font.inc, which src/game/keycap.c draws key caps from at run time.

    tools/glyphs/gen_keyfont.py            writes src/game/keycap_font.inc
    tools/glyphs/gen_keyfont.py --check    status 1 if the file on disk differs

A path is M, L, Q, A and Z as draw.py writes them (absolute); curves become short straight
pieces. Standard library only.
"""
import math
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import draw  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "src", "game", "keycap_font.inc")
TOKEN = re.compile(r"([MLQAZ])|(-?\d*\.?\d+(?:e-?\d+)?)")


def arc(x0, y0, rx, ry, large, sweep, x1, y1, steps=10):
    """SVG endpoint arc (no rotation) as points after (x0, y0)."""
    if rx == 0 or ry == 0:
        return [(x1, y1)]
    dx, dy = (x0 - x1) / 2.0, (y0 - y1) / 2.0
    lam = (dx / rx) ** 2 + (dy / ry) ** 2
    if lam > 1:
        rx, ry = rx * math.sqrt(lam), ry * math.sqrt(lam)
    num = (rx * ry) ** 2 - (rx * dy) ** 2 - (ry * dx) ** 2
    den = (rx * dy) ** 2 + (ry * dx) ** 2
    co = math.sqrt(max(0.0, num / den)) if den else 0.0
    if large == sweep:
        co = -co
    cxp, cyp = co * rx * dy / ry, -co * ry * dx / rx
    cx, cy = cxp + (x0 + x1) / 2.0, cyp + (y0 + y1) / 2.0
    a0 = math.atan2((dy - cyp) / ry, (dx - cxp) / rx)
    a1 = math.atan2((-dy - cyp) / ry, (-dx - cxp) / rx)
    da = a1 - a0
    if sweep and da < 0:
        da += 2 * math.pi
    if not sweep and da > 0:
        da -= 2 * math.pi
    return [(cx + rx * math.cos(a0 + da * i / steps), cy + ry * math.sin(a0 + da * i / steps))
            for i in range(1, steps + 1)]


def flatten(d):
    """A path as a list of polylines [(x, y), ...]."""
    t = [m.group(0) for m in TOKEN.finditer(d)]
    i, polys, cur, start, pos = 0, [], None, None, (0.0, 0.0)

    def num():
        nonlocal i
        v = float(t[i])
        i += 1
        return v

    cmd = None
    while i < len(t):
        if re.match(r"[MLQAZ]", t[i]):
            cmd = t[i]
            i += 1
            if cmd == "Z":
                if cur:
                    cur.append(start)
                pos = start
                continue
        if cmd == "M":
            pos = (num(), num())
            start = pos
            cur = [pos]
            polys.append(cur)
            cmd = "L"
        elif cmd == "L":
            pos = (num(), num())
            cur.append(pos)
        elif cmd == "Q":
            cx, cy, x, y = num(), num(), num(), num()
            for k in range(1, 9):
                u = k / 8.0
                cur.append(((1 - u) ** 2 * pos[0] + 2 * (1 - u) * u * cx + u * u * x,
                            (1 - u) ** 2 * pos[1] + 2 * (1 - u) * u * cy + u * u * y))
            pos = (x, y)
        elif cmd == "A":
            rx, ry, _rot, large, sweep, x, y = num(), num(), num(), int(num()), int(num()), num(), num()
            cur.extend(arc(pos[0], pos[1], rx, ry, large, sweep, x, y))
            pos = (x, y)
        else:
            raise ValueError("path %r" % d)
    return polys


def cname(c):
    return "'\\\\'" if c == "\\" else "'\\''" if c == "'" else "'%s'" % c


def build():
    pts, polys, glyphs, symbols = [], [], [], []

    def add(d):
        first = len(polys)
        for p in flatten(d):
            polys.append((len(pts) // 2, len(p)))
            for x, y in p:
                pts.extend((x, y))
        return first, len(polys) - first

    for c in sorted(draw.LETTERS):
        adv, d = draw.LETTERS[c]
        f, n = add(d)
        glyphs.append((c, adv, f, n))
    for name in sorted(draw.SYMBOL_PATHS):
        w, d = draw.SYMBOL_PATHS[name]
        f, n = add(d)
        symbols.append((name, w, f, n))
    o = ["/* Generated by tools/glyphs/gen_keyfont.py from the stroke alphabet of tools/glyphs/draw.py.",
         " * Not edited by hand: run the script (--check says whether this file is current). */",
         "static const float kf_pts[] = {"]
    for k in range(0, len(pts), 12):
        o.append("    " + ", ".join("%.4f" % v for v in pts[k:k + 12]) + ",")
    o.append("};")
    o.append("static const struct { uint16_t first, n; } kf_polys[] = {")
    for k in range(0, len(polys), 8):
        o.append("    " + ", ".join("{ %d, %d }" % p for p in polys[k:k + 8]) + ",")
    o.append("};")
    o.append("static const struct { char c; float adv; uint16_t first, n; } kf_glyphs[] = {")
    for c, adv, f, n in glyphs:
        o.append("    { %s, %.2ff, %d, %d }," % (cname(c), adv, f, n))
    o.append("};")
    o.append("static const struct { const char *name; float stroke; uint16_t first, n; } kf_symbols[] = {")
    for name, w, f, n in symbols:
        o.append('    { "%s", %.2ff, %d, %d },' % (name, w, f, n))
    o.append("};")
    return "\n".join(o) + "\n"


def main(argv):
    text = build()
    if len(argv) > 1 and argv[1] == "--check":
        try:
            same = open(OUT, encoding="utf-8").read() == text
        except OSError:
            same = False
        if not same:
            sys.stderr.write("keycap_font.inc differs: run tools/glyphs/gen_keyfont.py\n")
        return 0 if same else 1
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
