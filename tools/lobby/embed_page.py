#!/usr/bin/env python3
"""embed_page.py: stats_page.html + the icon -> stats_page.h (the page inside
the takedawn-lobby program), admin_page.html -> admin_page.h (the owner's
page), and optionally the finished pages as files.

    python3 tools/lobby/embed_page.py            # rewrite stats_page.h and admin_page.h
    python3 tools/lobby/embed_page.py --html OUT # also write the finished index.html
    python3 tools/lobby/embed_page.py --admin-html OUT  # and the owner's page

The header is committed, so building the server needs no Python.
"""
import argparse
import base64
import os

here = os.path.dirname(os.path.abspath(__file__))
ap = argparse.ArgumentParser()
ap.add_argument("--html")
ap.add_argument("--admin-html")
a = ap.parse_args()

icon = open(os.path.join(here, "..", "..", "assets", "icon", "takedawn.svg"), "rb").read()


def embed(src, header, symbol, guard, html_out):
    page = open(os.path.join(here, src), encoding="utf-8").read()
    page = page.replace("{{ICON}}", base64.b64encode(icon).decode())
    if html_out:
        open(html_out, "w", encoding="utf-8").write(page)
    out = ["/* Generated by tools/lobby/embed_page.py from %s: do not edit. */" % src,
           "#ifndef %s" % guard, "#define %s" % guard, "static const char %s[] =" % symbol]
    for line in page.encode("utf-8").split(b"\n"):
        toks = [chr(c) if 32 <= c < 127 and chr(c) not in '"\\?' else "\\%03o" % c for c in line]
        cur = ""
        for t in toks:                  # a string literal stays short (compiler limits)
            if len(cur) + len(t) > 1500:
                out.append('    "%s"' % cur)
                cur = ""
            cur += t
        out.append('    "%s\\n"' % cur)
    out[-1] = out[-1] + ";"
    out.append("#endif")
    open(os.path.join(here, header), "w").write("\n".join(out) + "\n")
    print("%s: %d bytes of page" % (header, len(page.encode("utf-8"))))


embed("stats_page.html", "stats_page.h", "k_stats_page", "STATS_PAGE_H", a.html)
embed("admin_page.html", "admin_page.h", "k_admin_page", "ADMIN_PAGE_H", a.admin_html)
