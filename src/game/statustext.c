const char *bo3_statustext(int lang, int id)
{
    const char *t;
    if (id < 0 || id >= BO3_TXT_N)
        return "";
    if (lang < 0 || lang >= BO3_LANG_COUNT)
        lang = BO3_LANG_ENGLISH;
    t = k_text[lang][id];
    return t && t[0] ? t : k_text[BO3_LANG_ENGLISH][id];
}
